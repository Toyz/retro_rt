/// An angle as `TURN` units a full turn, wrapping on every operation.
/// `TURN` must be a power of two of at least 4: [`Angle4096`], [`Bam`].
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct Angle<const TURN: u32>(u32);

/// 4096 units a turn: the PS1 GTE's angles.
pub type Angle4096 = Angle<4096>;

/// 65536 units a turn: the binary angle (BAM) of DOOM, the N64's libraries
/// and many games since.
pub type Bam = Angle<65536>;

impl<const TURN: u32> Angle<TURN> {
    const CHECK: () = assert!(TURN.is_power_of_two() && TURN >= 4, "TURN is a power of two of at least 4");

    /// No turn.
    pub const ZERO: Self = Angle(0);
    /// A quarter turn (90 degrees).
    pub const QUARTER: Self = Angle(TURN / 4);
    /// Half a turn (180 degrees).
    pub const HALF: Self = Angle(TURN / 2);

    /// An angle from its units, wrapped into `0..TURN` (negative units count
    /// back from a full turn).
    pub const fn new(units: i64) -> Self {
        let () = Self::CHECK;
        Angle((units & (TURN as i64 - 1)) as u32)
    }

    /// The units, `0..TURN`.
    pub const fn units(self) -> u32 {
        self.0
    }

    /// The units as a signed angle, `-TURN/2..TURN/2`.
    pub const fn signed(self) -> i32 {
        let half = TURN / 2;
        if self.0 >= half { self.0 as i32 - TURN as i32 } else { self.0 as i32 }
    }

    /// The nearest angle to `deg` degrees.
    pub fn from_degrees(deg: f64) -> Self {
        Angle::new((deg * f64::from(TURN) / 360.0).round() as i64)
    }

    /// The angle in degrees, `0.0..360.0`.
    pub fn degrees(self) -> f64 {
        f64::from(self.0) * 360.0 / f64::from(TURN)
    }

    /// The angle in radians, `0.0..2pi`.
    pub fn radians(self) -> f64 {
        f64::from(self.0) * std::f64::consts::TAU / f64::from(TURN)
    }

    /// The same angle with `OTHER` units a turn, rounded to the nearest.
    pub fn convert<const OTHER: u32>(self) -> Angle<OTHER> {
        let scaled = (u64::from(self.0) * u64::from(OTHER) + u64::from(TURN) / 2) / u64::from(TURN);
        Angle::<OTHER>::new(scaled as i64)
    }

    /// The angle in 4096ths of a turn, rounded to the nearest: the tables'
    /// resolution.
    fn index4096(self) -> u32 {
        self.convert::<4096>().0
    }

    /// The sine, from the quarter-wave table at 4096 a turn.
    pub fn sin(self) -> Q12 {
        let i = self.index4096();
        let q = (i % 1024) as usize;
        let v = match i / 1024 {
            0 => SIN[q],
            1 => SIN[1024 - q],
            2 => -SIN[q],
            _ => -SIN[1024 - q],
        };
        Q12::from_raw(i32::from(v))
    }

    /// The cosine: the sine a quarter turn on.
    pub fn cos(self) -> Q12 {
        (self + Self::QUARTER).sin()
    }

    /// `(x, y)` turned by this angle, counter-clockwise for y up: `x cos - y
    /// sin`, `x sin + y cos`, each product shifted right 12 as the GTE's
    /// rotation does.
    pub fn rotate(self, x: i32, y: i32) -> (i32, i32) {
        let (s, c) = (i64::from(self.sin().raw()), i64::from(self.cos().raw()));
        let (x, y) = (i64::from(x), i64::from(y));
        (((x * c - y * s) >> 12) as i32, ((x * s + y * c) >> 12) as i32)
    }
}

impl<const TURN: u32> Add for Angle<TURN> {
    type Output = Self;
    fn add(self, o: Self) -> Self {
        Angle((self.0 + o.0) & (TURN - 1))
    }
}

impl<const TURN: u32> AddAssign for Angle<TURN> {
    fn add_assign(&mut self, o: Self) {
        *self = *self + o;
    }
}

impl<const TURN: u32> Sub for Angle<TURN> {
    type Output = Self;
    fn sub(self, o: Self) -> Self {
        Angle(self.0.wrapping_sub(o.0) & (TURN - 1))
    }
}

impl<const TURN: u32> SubAssign for Angle<TURN> {
    fn sub_assign(&mut self, o: Self) {
        *self = *self - o;
    }
}

impl<const TURN: u32> Neg for Angle<TURN> {
    type Output = Self;
    fn neg(self) -> Self {
        Angle(self.0.wrapping_neg() & (TURN - 1))
    }
}

/// The angle of the point `(x, y)` from the positive x axis, counter-clockwise
/// for y up, in 4096ths of a turn: within one unit of the true angle. The
/// origin gives 0.
pub fn atan2(y: i32, x: i32) -> Angle4096 {
    if x == 0 && y == 0 {
        return Angle::ZERO;
    }
    let (ax, ay) = (i64::from(x).unsigned_abs(), i64::from(y).unsigned_abs());
    // The angle within the first octant, from the smaller over the larger.
    let (small, big) = if ay <= ax { (ay, ax) } else { (ax, ay) };
    let idx = ((small * 1024 + big / 2) / big) as usize;
    let mut a = i64::from(ATAN[idx]);
    if ay > ax {
        a = 1024 - a;
    }
    if x < 0 {
        a = 2048 - a;
    }
    if y < 0 {
        a = -a;
    }
    Angle::new(a)
}

/// The integer square root: the largest `r` with `r * r <= n`. Exact for
/// every `u64`.
pub fn isqrt(n: u64) -> u64 {
    n.isqrt()
}

/// The square root of a [`Q12`]: the [`Q12`] nearest below the true root.
/// A negative value gives 0.
pub fn sqrt_q12(v: Q12) -> Q12 {
    let raw = u64::try_from(v.raw()).unwrap_or(0);
    Q12::from_raw(isqrt(raw << 12) as i32)
}

/// The length of `(x, y)`, rounded down: exact integer arithmetic.
pub fn hypot(x: i32, y: i32) -> u32 {
    let (x, y) = (i64::from(x), i64::from(y));
    isqrt((x * x + y * y) as u64) as u32
}

