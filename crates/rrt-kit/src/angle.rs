//! Angles and trigonometry in integers, as the consoles did them: an angle
//! is a fraction of a turn, sine and cosine come out of a table as
//! [`Q12`] (4096 is 1.0), and square roots are exact integers.
//!
//! [`Angle<TURN>`] holds an angle as `TURN` units a turn, wrapping:
//! [`Angle4096`] is the PS1 GTE's (`rsin`/`rcos` take 4096 a turn),
//! [`Bam`] the 65536-a-turn binary angle of DOOM, the N64's libraries and
//! many others. [`Angle::sin`] and [`Angle::cos`] read a quarter-wave table
