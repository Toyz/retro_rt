/// The rows of `c`'s glyph; a character outside printable ASCII draws as `?`.
pub fn glyph(c: char) -> &'static [u8; 13] {
    let i = if (' '..='~').contains(&c) { c as usize - 0x20 } else { '?' as usize - 0x20 };
    &GLYPHS[i]
}

/// Draws `text` with its top-left at (`x`, `y`) in `rgba`, each font pixel a
/// `scale` x `scale` block (0 is taken as 1), clipped to the picture. Only
/// set pixels are drawn: the background shows through. A newline starts a
/// new line under the first. Returns the x after the last character.
pub fn draw(p: &mut Picture, x: u32, y: u32, text: &str, rgba: [u8; 4], scale: u32) -> u32 {
    let s = scale.max(1);
    let (mut cx, mut cy) = (x, y);
    for c in text.chars() {
        if c == '\n' {
            (cx, cy) = (x, cy + HEIGHT * s);
            continue;
        }
        for (row, bits) in glyph(c).iter().enumerate() {
            for col in 0..WIDTH {
                if (bits >> (WIDTH - 1 - col)) & 1 == 1 {
                    p.fill_rect(cx + col * s, cy + row as u32 * s, s, s, rgba);
                }
            }
        }
        cx += WIDTH * s;
    }
    cx
}

/// The size `text` takes at `scale`: the widest line's width, the lines'
/// height.
pub fn measure(text: &str, scale: u32) -> (u32, u32) {
    let s = scale.max(1);
    let lines: Vec<&str> = text.split('\n').collect();
    let w = lines.iter().map(|l| l.chars().count() as u32).max().unwrap_or(0);
    (w * WIDTH * s, lines.len() as u32 * HEIGHT * s)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The capital A, as the font file draws it.
    #[test]
    fn the_capital_a_is_the_fonts() {
        let rows: Vec<String> = glyph('A')
            .iter()
            .map(|r| (0..6).map(|c| if (r >> (5 - c)) & 1 == 1 { '#' } else { '.' }).collect())
            .collect();
        let want = ["..#...", ".#.#..", "#...#.", "#...#.", "#...#.", "#####.", "#...#.", "#...#.", "#...#."];
        assert_eq!(rows[2..11], want);
        assert_eq!(glyph(' '), &[0; 13]);
        assert_eq!(glyph('\u{e9}'), glyph('?'), "outside ASCII draws as ?");
    }

    #[test]
    fn drawing_sets_only_glyph_pixels_scaled_and_clipped() {
        let mut p = Picture::filled(20, 30, [0, 0, 0, 0]);
        let end = draw(&mut p, 0, 0, "A", [255; 4], 2);
        assert_eq!(end, 12);
        assert_eq!(p.get(4, 4), Some([255; 4]), "A's apex, row 2 col 2, at scale 2");
        assert_eq!(p.get(0, 0), Some([0; 4]), "background untouched");
        let mut small = Picture::filled(3, 3, [0; 4]);
        draw(&mut small, 0, 0, "W", [255; 4], 4);
        assert_eq!(measure("ab\nc", 1), (12, 26));
        assert_eq!(measure("", 2), (0, 26));
    }
}
